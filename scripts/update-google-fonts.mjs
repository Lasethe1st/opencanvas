// Refreshes the bundled Google Fonts snapshot used when the live catalogue can't be fetched.
// Run `npm run build:electron` first; usage: node scripts/update-google-fonts.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { parseGoogleMetadata } = require('../dist-electron/harness.cjs');
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const res = await fetch('https://fonts.google.com/metadata/fonts');
if (!res.ok) throw new Error(`HTTP ${res.status}`);
const fonts = parseGoogleMetadata(await res.text()).slice(0, 150);
const rows = fonts.map((f) => `  ${JSON.stringify(f)},`).join('\n');
const out = `// Generated by scripts/update-google-fonts.mjs: the most popular Google Fonts, used offline.
import type { GoogleFont } from './fonts';

export const BUNDLED_GOOGLE_FONTS: GoogleFont[] = [
${rows}
];
`;
fs.writeFileSync(path.join(root, 'shared', 'google-fonts-fallback.ts'), out);
console.log(`Wrote ${fonts.length} fonts.`);
